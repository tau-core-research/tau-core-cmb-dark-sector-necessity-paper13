def rel(path: Path) -> str:
    return str(path.resolve().relative_to(ROOT))


def write_table(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(ROWS[0].keys()))
        writer.writeheader()
        writer.writerows(ROWS)


def build_summary(table_path: Path) -> dict[str, Any]:
    return {
        "report_id": "cmb_tau_lensing_projection_output_replay_spec_scaffold_summary_v01",
        "claim_boundary": "projection_output_replay_spec_scaffold_only_no_grid_no_replay_no_score_no_dark_sector_verdict",
        "table": rel(table_path),
        "target": "source-to-3000-grid physical projection replay",
        "status": "OUTPUT_REPLAY_SPEC_DECLARED_NOT_FILLED",
        "rows": len(ROWS),
        "missing_or_unproved_rows": [row["row_id"] for row in ROWS],
        "not_covered_by": "adapter replay B_ACT @ grid -> 18-vector",
        "unblocks_when": [
            "physical projection equation, kernel/measure, and normalization are accepted",
            "route and exact L axis are declared",
            "finite 3000-row grid is generated by replay",
            "zero-limit replay and post-population firewall pass",
        ],
        "score_run": False,
        "physical_tau_score_run": False,
        "dark_sector_verdict": False,
    }


def write_doc(summary: dict[str, Any], path: Path) -> None:
    rows = "\n".join(
        (
            f"- `{row['row_id']}` `{row['component']}`: {row['current_status']} | "
            f"required: {row['required_content']} | failure if: {row['failure_if']}"
        )
        for row in ROWS
    )
    unblocks = "\n".join(f"- {item}" for item in summary["unblocks_when"])
    text = f"""# CMB Tau Lensing Projection Output/Replay Spec Scaffold v01

**Doc class:** projection output/replay spec scaffold
**Reader role:** Paper 13 Tau-grid implementer
**Status:** output/replay schema declared; no grid accepted; not a score
**Canonical parent:** `docs/cmb_tau_lensing_physical_projection_replay_requirement_v01.md`

## Claim Boundary

```text
{summary["claim_boundary"]}
```

## Target

```text
{summary["target"]}
```

This is not covered by:

```text
{summary["not_covered_by"]}
```

## Required Rows

{rows}

## Unblocks When

{unblocks}
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main() -> None:
    parser = argparse.ArgumentParser(description="Build projection output/replay spec scaffold.")
    parser.add_argument("--write-table", nargs="?", const=str(DEFAULT_TABLE))
    parser.add_argument("--write-summary", nargs="?", const=str(DEFAULT_SUMMARY))
    parser.add_argument("--write-doc", nargs="?", const=str(DEFAULT_DOC))
    args = parser.parse_args()
    table_path = Path(args.write_table or DEFAULT_TABLE)
    if args.write_table:
        write_table(table_path)
    summary = build_summary(table_path)
    if args.write_summary:
        path = Path(args.write_summary)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")
    if args.write_doc:
        write_doc(summary, Path(args.write_doc))
    print(json.dumps(summary, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
